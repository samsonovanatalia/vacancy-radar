{#
    Заголовок вакансии к общему виду — для склейки одной и той же вакансии,
    записанной по-разному в разных источниках и в разных городах.

    Зачем и чем это отличается от прежнего правила:

    Раньше ядро заголовка получали обрезкой до первого разделителя:
    «Data Engineer - Payments (m/w/d)» → «data engineer». Правило дешёвое,
    но оно режет вместе с шумом и смысл. Замерено 2026-09-20: у N26 четыре
    разные вакансии — Data Analyst по Everyday Banking, Finance, Investments
    и Ops Automation — схлопывались в одну, и в подборку попадала одна из
    четырёх. Всего так пряталось 7 дата-вакансий.

    Теперь наоборот: ключ — это заголовок ЦЕЛИКОМ, из которого вычищен
    только шум. Что шум, перечислено ниже закрытыми списками. Специализация
    («- Finance», «(CRM)», «– Market Risk») шумом не считается и в ключе
    остаётся, поэтому такие вакансии больше не склеиваются.

    Цена: вакансия, которую источник выложил дважды с разным хвостом
    («Data Engineer» и «Data Engineer - Payments»), теперь приедет дважды.
    Это осознанный размен, тот же, что записан в normalize_company_name:
    лишнее сообщение стоит дёшево, а ложная склейка прячет вакансию
    навсегда — она уходит как duplicate и не показывается никогда.

    Где используется:
      mart_vacancies_scored — title_key, половина ключа дедупа.

    Макрос возвращает не запрос, а выражение: при компиляции dbt подставляет
    его текст на место вызова {{ normalize_job_title('колонка') }}.
    Шаги собраны через set сверху вниз, каждый следующий оборачивает
    предыдущий — так же, как в clean_html_text и normalize_company_name.

    На вход ждёт заголовок УЖЕ в нижнем регистре (title_normalized из
    staging). Регистр здесь не трогаем, чтобы не делать одну работу дважды.
#}

{% macro normalize_job_title(column) %}

    {#
        Шаг 1. Маркеры пола — в любом месте строки и со скобками или без.

        Встречаются: (m/w/d), (m/f/d), (w/m/d), (f/m/x), h/f, (f/h), m/f,
        «all genders», «(all genders)». Пишут их и с пробелами внутри:
        «(m / w / d)».

        Буквы берём из набора [mwfdhx] — первые буквы слов männlich,
        weiblich, female, divers, homme, x. Нужно минимум два таких куска
        через косую черту, поэтому {1,2} после группы: одинокая буква «m»
        маркером не считается, иначе пострадал бы любой заголовок с «m».

        \b с обеих сторон обязательна: без неё «x» поймалась бы внутри слов.
    #}
    {%- set without_gender -%}
        regexp_replace(
            {{ column }},
            r'\(?\s*\b([mwfdhx](\s*/\s*[mwfdhx]){1,2}|all genders|any gender)\b\s*\)?',
            ' '
        )
    {%- endset -%}

    {#
        Шаг 2. Ставки и зарплаты в заголовке.

        Встречаются два вида: дневная («- €280 - €300 A Day») и годовая
        («45.000 - 55.000 € brutto/Jahr», «€45k»). Ловим по денежному знаку
        или коду валюты рядом с числом, вместе с хвостом вида «a day»,
        «per year», «brutto/jahr», «al año».

        Сначала диапазон «число - число знак», потом одиночное «знак число».
        Порядок важен: иначе от «280 - 300 €» осталось бы «280 -».
    #}
    {%- set without_salary -%}
        regexp_replace(
            regexp_replace(
                {{ without_gender }},
                r'[€$£]?\s*\d[\d.,]*\s*(k\b)?\s*[-–—]\s*[€$£]?\s*\d[\d.,]*\s*(k\b)?\s*(€|eur|usd|gbp)?(\s*(a day|per day|al día|per year|a year|al año|p\.?a\.?|brutto\s*/?\s*jahr|gross))?',
                ' '
            ),
            r'([€$£]|\b(eur|usd|gbp)\b)\s*\d[\d.,]*\s*(k\b)?(\s*(a day|per day|al día|per year|a year|al año|p\.?a\.?|brutto\s*/?\s*jahr|gross))?',
            ' '
        )
    {%- endset -%}

    {#
        Шаг 3. Города и страны — В ЛЮБОМ МЕСТЕ строки, а не только в конце.

        Именно здесь споткнулся первый прототип: он чистил только хвост, и
        у Careerwise «Data Analyst - Barcelona, Cataluña, Spain - €280…»
        после снятия ставки осталось «data analyst barcelona», а парная
        вакансия называлась просто «Data Analyst». Верная склейка
        разъезжалась. У Zynga же город стоит В НАЧАЛЕ: «Barcelona, Spain
        Zynga Principal Data Analyst».

        Список закрытый: города, по которым мы ищем, плюс Испания и
        Каталония. Не «любое географическое слово» — иначе пострадали бы
        названия продуктов и команд.

        \b с обеих сторон: «malaga» не должна ловиться внутри другого слова.
    #}
    {%- set without_place -%}
        regexp_replace(
            {{ without_salary }},
            r'\b(barcelona|madrid|valencia|sevilla|bilbao|malaga|málaga|zaragoza|cataluña|catalunya|spain|espana|españa)\b',
            ' '
        )
    {%- endset -%}

    {#
        Шаг 4. Разделители и пробелы.

        После трёх вычисток в строке остаются висячие дефисы, скобки и
        запятые: «data analyst - , - » . Меняем на пробел ВСЁ, что не буква
        и не цифра, потом схлопываем пробелы и обрезаем края.

        Заодно это снимает разницу в пунктуации между источниками: у Sanofi
        один и тот же заголовок пришёл с «-» и с «—», у Cigna — «IT» против
        «It». Регистр уже снят на входе.

        Буквы с диакритикой перечислены явно: [^a-z0-9 ] выбросил бы «ñ»
        и «é», и «diseño» превратилось бы в «dise o».
    #}
    {%- set squeezed -%}
        trim(regexp_replace(
            regexp_replace({{ without_place }}, r'[^a-z0-9àáâäãéèêëíìîïóòôöõúùûüñç ]', ' '),
            r'\s+', ' '
        ))
    {%- endset -%}

    {#
        Шаг 5. Пустой результат — в null.

        От заголовка может не остаться ничего: «(m/w/d)» целиком, «Barcelona»
        целиком. Пустая строка в ключе дедупа склеила бы все такие вакансии
        в одну группу, а null в partition by — тоже одна группа, поэтому на
        стороне витрины стоит coalesce на исходный заголовок.
    #}
    nullif({{ squeezed }}, '')

{% endmacro %}
