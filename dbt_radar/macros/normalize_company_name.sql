{#
    Название компании к общему виду — для склейки одной и той же компании,
    записанной по-разному в разных источниках.

    Зачем: ключ дедупа в mart_vacancies_scored собирается из компании и ядра
    заголовка. Пока компания бралась как lower(company_name), «Gartner» и
    «Gartner, Inc.» считались разными компаниями, и одна и та же вакансия
    приходила дважды. Замерено 2026-09-20: 29 таких групп, 121 строка.

    Где используется:
      mart_vacancies_scored — company_core, часть ключа дедупа.
    Пока место одно, но макрос всё равно: правило «что такое одна и та же
    компания» должно жить в одном месте, иначе через месяц оно разойдётся
    между витриной и каким-нибудь отчётом. Так же сделан clean_html_text.

    Макрос возвращает не запрос, а выражение: при компиляции dbt подставляет
    его текст на место вызова {{ normalize_company_name('колонка') }}.
    Шаги собраны через set сверху вниз, каждый следующий оборачивает
    предыдущий.

    Чего макрос НЕ делает намеренно:
      — не склеивает слова: «wppproduction» и «wpp production» останутся
        разными. Убрать все пробелы значило бы склеить и «Data Corp» с
        «Datacorp», а это уже угадывание;
      — не трогает слова вроде holding, partners, technologies: «Axa Partners»
        и «Axa Partners Holding SA» останутся разными. Список этих слов
        открытый, и каждое новое вычёркивание повышает риск склеить две
        разные компании;
      — не переводит юридическую форму в середине названия: убираем суффиксы
        только с конца, иначе пострадает журнал «Inc Magazine».

    Цена ошибки несимметрична: пропущенный дубль стоит одного лишнего
    сообщения в дайджесте, а ЛОЖНАЯ склейка прячет вакансию навсегда —
    она уйдёт как duplicate и никогда не покажется. Поэтому список короткий.
#}

{% macro normalize_company_name(column) %}

    {#
        Шаг 1. Нижний регистр, точки и запятые прочь, пробелы схлопнуты.

        Точки именно УДАЛЯЕМ, а не меняем на пробел: так «e.v.» становится
        «ev» и попадает в список суффиксов ниже, а «inc.» — в «inc».
        Плата за это: «feld.energy» превращается в «feldenergy» и с
        «feld energy» уже не сойдётся. Оба варианта не бесплатны, выбран
        тот, который закрывает больше случаев в наших данных.
    #}
    {%- set cleaned -%}
        trim(regexp_replace(
            regexp_replace(lower({{ column }}), r'[.,]', ''),
            r'\s+', ' '
        ))
    {%- endset -%}

    {#
        Шаг 2. Юридические суффиксы с конца.

        (\s(...))+$ — один или несколько подряд: «gartner inc» → «gartner»,
        «foo holding bv nv» → «foo holding». Плюс на конце нужен потому,
        что у части названий форма написана дважды.

        Только с КОНЦА (якорь $) и только отдельным словом (\s перед ним):
        иначе «Inc Magazine» осталось бы «magazine», а «Sage» пострадало бы
        от «ag». Границу слева даёт \s, границу справа — $.

        Список закрытый и короткий — тот, что просили: inc, ltd, llc, corp,
        gmbh, ag, sa, sl, bv, nv, ev (из «e.v.» после шага 1). Новую форму
        добавляют сюда отдельным словом, увидев её в данных.
    #}
    {%- set without_suffix -%}
        regexp_replace(
            {{ cleaned }},
            r'(\s(inc|ltd|llc|corp|gmbh|ag|sa|sl|bv|nv|ev))+$',
            ''
        )
    {%- endset -%}

    {#
        Шаг 3. the и group по краям.

        «The Cigna Group» → «cigna». Сначала суффиксы (шаг 2), потом эти
        слова: у «Foo Group Inc» сначала отваливается inc, и только тогда
        group оказывается на краю и тоже отваливается.

        Только по краям, не везде: «Group Nine Media» — это название, а не
        форма, и «the» в середине тоже бывает частью имени.
    #}
    {%- set without_edges -%}
        regexp_replace(
            regexp_replace({{ without_suffix }}, r'^(the|group)\s+', ''),
            r'\s+(the|group)$',
            ''
        )
    {%- endset -%}

    {#
        Шаг 4. Обрезать края ещё раз: после вычёркиваний мог остаться пробел.
        nullif на пустую строку: если от названия не осталось ничего (такое
        возможно у компании с именем «The Group»), пусть будет null, а не ''.
        Пустая строка склеила бы все такие компании в одну группу.
    #}
    nullif(trim({{ without_edges }}), '')

{% endmacro %}
