-- Сингулярный тест: запрос должен вернуть НОЛЬ строк. Каждая найденная
-- строка — вакансия, в чистом описании которой остался мусор, и dbt build
-- упадёт с их числом.
--
-- Тесты unique и not_null описываются одной строкой в yml и подходят
-- к любой колонке. Проверку «в тексте не осталось HTML» так не описать,
-- поэтому она — отдельный запрос в папке tests.
--
-- Что ищем:
--   </?[a-zA-Z][^>]*>          — тег, который пережил чистку;
--   <[a-zA-Z][^>]*$            — оборванный тег без «>» в конце текста;
--   &(?:[a-z]+|#\d+|#x...);    — нераскрытая сущность. Имя только строчными
--                                буквами: так «W&B;» в тексте вакансии про
--                                ML-инструменты не считается сущностью;
--   on Arbeitnow$              — рекламный хвост arbeitnow в конце текста.

select
    vacancy_key,
    substr(description_clean, 1, 200)               as description_clean_start
from {{ ref('stg_vacancies') }}
where regexp_contains(
    description_clean,
    r'</?[a-zA-Z][^>]*>|<[a-zA-Z][^>]*$|&(?:[a-z]+|#\d+|#x[0-9a-fA-F]+);|on Arbeitnow$'
)
