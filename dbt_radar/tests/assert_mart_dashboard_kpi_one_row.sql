-- Сингулярный тест: в mart_dashboard_kpi ровно одна строка.
--
-- Запрос возвращает строку, только если строк не одна, — тогда dbt build
-- упадёт. Встроенного теста «число строк» в dbt без пакетов нет
-- (dbt_utils.expression_is_true и подобные — из пакета), поэтому отдельный
-- запрос, как assert_description_clean_has_no_html.
--
-- Зачем, если агрегат без group by и так даёт одну строку: карточки на
-- дашборде берут значение без группировки. Если кто-то добавит сюда
-- group by или join, который размножит строки, Looker молча сложит их,
-- и числа на сводке станут неверными.

select
    count(*)                                            as rows_count
from {{ ref('mart_dashboard_kpi') }}
having count(*) != 1
