-- Таблица raw.digest_sent: журнал исходов отправки вакансий в Telegram.
--
-- Создаётся этим скриптом, а не dbt: это сырой слой, dbt его только читает
-- (источник digest_sent в dbt_radar/models/staging/_sources.yml).
-- Пишет бот (notify/telegram.py): строка на каждую вакансию с окончательным
-- исходом. Временные сбои (429, 5xx, сеть) не пишутся — вакансия остаётся в
-- очереди и уйдёт в следующий раз.
--
-- Колонки:
--   vacancy_key — ключ вакансии;
--   sent_at     — когда записан исход: время доставки или отказа Telegram;
--   status      — sent — доставлена; undeliverable — Telegram отказал с
--                 кодом 400, и повторять бессмысленно.
--
-- append-only: строки только дописываются, не меняются и не удаляются.
-- Средствами BigQuery такой запрет не задать — это договорённость для кода
-- бота: insert, но не update, delete или merge. Записал вакансию повторно —
-- новая строка; повторы схлопывает stg_digest_sent.
--
-- not null на vacancy_key и sent_at: строка без ключа или без даты ничего не
-- значит. Пусть BigQuery откажет в такой записи, а не примет пустоту.
--
-- status — без not null. Колонку добавили, когда в таблице уже были строки,
-- а обязательную колонку в существующую таблицу BigQuery добавить не даёт.
-- У старых строк status null: тогда бот писал только доставленное, и
-- stg_digest_sent читает null как sent. В create table status тоже без
-- not null — чтобы таблица на новом проекте не отличалась от старой.
--
-- Без партиций, в отличие от остальных raw-таблиц: в день прибавится не больше
-- 25 строк, а очередь каждый раз читает всю историю — разбиение по дням не
-- сэкономит ни байта.
--
-- if not exists в обеих командах: повторный запуск ничего не сломает и данные
-- не сотрёт. На новом проекте create создаст таблицу сразу со status, и alter
-- ничего не сделает; на старом — наоборот.
--
-- Как запустить: вставить в консоль BigQuery или
--     bq query --use_legacy_sql=false < sql/raw_digest_sent.sql

create table if not exists `raw.digest_sent` (
    vacancy_key string not null,
    sent_at     timestamp not null,
    status      string
);

alter table `raw.digest_sent`
    add column if not exists status string;
