-- Таблица raw.digest_runs: журнал запусков дайджеста, строка на каждый запуск.
--
-- Создаётся этим скриптом, а не dbt: это сырой слой, dbt его только читает
-- (источник digest_runs в dbt_radar/models/staging/_sources.yml).
-- Пишет бот (notify/telegram.py) в конце каждого запуска — и когда очередь
-- пуста, и когда запуск упал, и когда он вышел, потому что сегодня дайджест
-- уже был.
--
-- Зачем, если есть raw.digest_sent: там строка на вакансию, и день без
-- вакансий в нём не виден вовсе — неотличим от дня, когда бот не запускался.
-- Здесь строка на запуск, и пустой день — это строка со status = 'empty'.
--
-- Колонки:
--   run_at             — когда запуск закончился, UTC;
--   run_date           — день запуска по Барселоне: по нему бот проверяет,
--                        был ли сегодня дайджест, а витрина ищет пропуски;
--   status             — sent    — доставлена хотя бы одна вакансия;
--                        empty   — очередь пуста, ушло «новых вакансий нет»;
--                        failed  — не доставлено ничего или запуск упал;
--                        skipped — сегодня уже был запуск sent или empty,
--                                  этот вышел, ничего не отправив;
--   queue_size         — длина очереди; null, если до очереди не дошли;
--   sent_count         — сколько вакансий доставлено;
--   is_forced          — запуск с --force, мимо проверки «сегодня уже был».
--
-- append-only, как digest_sent: только insert.
--
-- Партиции по run_date, в отличие от digest_sent. В песочнице таблица без
-- партиций удаляется целиком через 60 дней после создания, а таблица с
-- партициями теряет только партиции старше 60 дней. Старые запуски не нужны:
-- витрина смотрит 14 дней, бот — сегодняшний. А вот пропавшая таблица
-- уронила бы бота на первом же запросе.
--
-- Как запустить: вставить в консоль BigQuery или
--     bq query --use_legacy_sql=false < sql/raw_digest_runs.sql

create table if not exists `raw.digest_runs` (
    run_at      timestamp not null,
    run_date    date not null,
    status      string not null,
    queue_size  int64,
    sent_count  int64 not null,
    is_forced   bool not null
)
partition by run_date;
